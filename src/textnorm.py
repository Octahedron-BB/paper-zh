"""中文译文的后处理规范化。

单独成层的原因：这些规则与术语表无关、与 LLM 无关，而且**不进缓存**
（缓存只存 LLM 的原始输出），所以改动它们永远是零 API 成本、不需要版本号。

为什么必须做：同一份文档里 LLM 会同时写出 `2,373` 和 `2，373` 两种写法。
中文排版规范里数值的千分位用半角逗号；更实际的问题是 TTS 会把全角逗号
读成停顿 —— `2，373` 会被读成「二，三百七十三」，数字直接读错。
"""
from __future__ import annotations

import re

# 全角数字 -> 半角。只动数字，不动标点（全角逗号在中文正文里是合法的句读）。
_FW_DIGITS = str.maketrans("０１２３４５６７８９", "0123456789")

# 数字之间的分隔符 -> 半角逗号。
# ⚠️ 必须限定「后面正好 3 位数字」，否则会把中文列举的 `1，2，3` 也改掉；
#    也不能用 \b 收尾 —— Python 的 \w 匹配中文，`2，373例` 的 `3` 和 `例` 之间没有词边界。
_THOUSANDS = re.compile(r"(?<=\d)[，､．](?=\d{3}(?!\d))")

# 口语稿里 LLM 会偶发地重复一个词（实测 `think/no-think 任务 任务`）。念出来很明显。
# ⚠️ 三个限定条件都是为了不误伤：
#   ① 只匹配中文词（不动英文）；
#   ② 分隔符只允许空格/制表符，**不允许换行** —— 否则会把两段粘在一起；
#   ③ 中间必须有空格：汉语合法的叠词（`慢慢`、`许多许多`）是不带空格的，
#      所以这条规则不会碰它们，而 LLM 的重复几乎总是带空格。
_DUP_CJK = re.compile(r"([\u4e00-\u9fff]{2,6})[ \t]+\1")


# 一段连续的拉丁字母/数字（可含连字符与点）算作**一个**阅读单位。
# ⚠️ 类里必须同时含字母与数字，不能写成 `[A-Za-z]...|[0-9]...` 两个分支：
#    那样 `53BP1` 会被切成 `53` + `BP1` 两段，与 prompt 里"缩写算 1 个字"的口径不符。
_LATIN_RUN = re.compile(r"[A-Za-z0-9][A-Za-z0-9\-\.]*")


def reading_len(text: str) -> int:
    """估算一句中文"读起来有多长"：**一串连续的拉丁字母/数字算 1 个字**。

    ⚠️ 为什么不直接用 `len()`：`BRCA1-BARD1 与 53BP1 轴拮抗决定 HR 或 NHEJ 的选择。`
    的 `len()` 是 **40**，但读起来只有 **15** 个字 —— 用 `len()` 当判据会把这种
    **很好**的句子误判为超标。本项目已反复栽在"**检查器的判据本身要先验证**"上。

    口径与 `prompts.DIGEST_SYSTEM` 里写给模型的那条（"英文缩写每个按 1 个汉字估算"）
    **刻意保持一致**：检查器与 prompt 用两套尺子的话，"看着都合格"就是假的。

    已知不精确处：`2026年` 会被算成 2 个字（实际上占 5 列宽）。取这个近似是为了
    口径统一；速览提要的句子里纯数字很少单独成串，影响可忽略。
    """
    if not text:
        return 0
    return len(re.sub(r"\s+", "", _LATIN_RUN.sub("X", text)))


def normalize_zh(text: str) -> str:
    """统一数字格式并折叠偶发重复词（幂等，可重复调用）。"""
    if not text:
        return text
    text = _DUP_CJK.sub(r"\1", text)
    return _THOUSANDS.sub(",", text.translate(_FW_DIGITS))
